"""Train the EMG MLP and export an integer-only model for TFLite Micro."""

import argparse
import csv
import json
import os
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np

from data import (CHANNELS, CSV_COLUMNS, FEATURE_COUNT, LABELS, PROFILES,
                  extract_features, get_profile, make_windows,
                  quantize_features, read_trials, split_trials)
from pyomyo_input import read_manifest


def build_model(tf):
    """1,157 trainable parameters; ReLUs fuse into the dense operations."""
    model = tf.keras.Sequential([
        tf.keras.Input(shape=(FEATURE_COUNT,), name="emg_features"),
        tf.keras.layers.Dense(32, activation="relu"),
        tf.keras.layers.Dense(16, activation="relu"),
        tf.keras.layers.Dense(len(LABELS), activation="softmax", name="commands"),
    ], name="emg_classifier")
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
                  loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    return model


def write_cpp_model(output_dir, model_bytes):
    (output_dir / "emg_model_data.h").write_text(
        "// Generated by train.py. See metadata.json for training provenance.\n"
        "#ifndef EMG_MODEL_DATA_H_\n#define EMG_MODEL_DATA_H_\n\n"
        "extern const unsigned char g_emg_model_data[];\n"
        "extern const unsigned int g_emg_model_data_len;\n\n#endif\n")
    rows = ["  " + ", ".join(f"0x{value:02x}" for value in model_bytes[i:i + 12]) + ","
            for i in range(0, len(model_bytes), 12)]
    (output_dir / "emg_model_data.cpp").write_text(
        '// Generated by train.py. See metadata.json for training provenance.\n'
        '#include "emg_model_data.h"\n\n'
        'alignas(16) const unsigned char g_emg_model_data[] = {\n' +
        "\n".join(rows) + "\n};\n"
        "const unsigned int g_emg_model_data_len = sizeof(g_emg_model_data);\n")


def evaluate_int8(tf, model_bytes, features):
    interpreter = tf.lite.Interpreter(model_content=model_bytes)
    interpreter.allocate_tensors()
    input_info, = interpreter.get_input_details()
    output_info, = interpreter.get_output_details()
    for info, expected_shape in ((input_info, [1, FEATURE_COUNT]),
                                 (output_info, [1, len(LABELS)])):
        if info["dtype"] != np.int8 or info["shape"].tolist() != expected_shape:
            raise ValueError("Export must have int8 [1,16] input and int8 [1,5] output")
    scale, zero_point = input_info["quantization"]
    quantized = quantize_features(features, scale, zero_point)
    scores = []
    for sample in quantized:
        interpreter.set_tensor(input_info["index"], sample[None, :])
        interpreter.invoke()
        scores.append(interpreter.get_tensor(output_info["index"])[0].copy())
    quantization = {
        "input": {"scale": float(scale), "zero_point": int(zero_point)},
        "output": {"scale": float(output_info["quantization"][0]),
                   "zero_point": int(output_info["quantization"][1])},
    }
    return np.stack(scores), quantization


def classification_metrics(labels, predictions):
    confusion = np.zeros((len(LABELS), len(LABELS)), dtype=np.int64)
    np.add.at(confusion, (labels, predictions), 1)
    return {"accuracy": float(np.mean(labels == predictions)),
            "confusion_matrix_actual_rows_predicted_columns": confusion.tolist()}


def train(args):
    profile = get_profile(args.mode)
    trials = (read_manifest(args.pyomyo_manifest, args.mode) if args.pyomyo_manifest
              else read_trials(args.data, args.mode))
    parts = split_trials(trials, args.validation_session, args.test_session)
    datasets, counts = {}, {}
    for name, part in parts.items():
        windows, labels = make_windows(part, args.mode)
        class_counts = np.bincount(labels, minlength=len(LABELS))
        missing = [LABELS[i] for i, count in enumerate(class_counts) if count == 0]
        if missing:
            raise ValueError(f"{name}: no complete windows for {missing}")
        datasets[name] = (windows, extract_features(windows, args.mode), labels)
        counts[name] = dict(zip(LABELS, class_counts.tolist()))
    # Validate the data before loading the larger training dependency.
    import tensorflow as tf

    tf.keras.utils.set_random_seed(args.seed)
    model = build_model(tf)
    _, train_x, train_y = datasets["train"]
    _, val_x, val_y = datasets["validation"]
    test_windows, test_x, test_y = datasets["test"]
    class_counts = np.bincount(train_y, minlength=len(LABELS))
    class_weight = {i: float(len(train_y) / (len(LABELS) * count))
                    for i, count in enumerate(class_counts)}
    model.summary()
    history = model.fit(
        train_x, train_y, validation_data=(val_x, val_y),
        epochs=args.epochs, batch_size=args.batch_size, class_weight=class_weight,
        callbacks=[tf.keras.callbacks.EarlyStopping(
            monitor="val_loss", patience=10, restore_best_weights=True)], verbose=2)

    # Calibration uses training data only, with representatives from every class.
    rng = np.random.default_rng(args.seed)
    calibration_indices = np.concatenate([
        rng.choice(np.flatnonzero(train_y == label),
                   size=min(100, int(class_counts[label])), replace=False)
        for label in range(len(LABELS))
    ])

    def representative_dataset():
        for index in calibration_indices:
            yield [train_x[index:index + 1]]

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = representative_dataset
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    model_bytes = converter.convert()
    scores, quantization = evaluate_int8(tf, model_bytes, test_x)
    float_predictions = model.predict(test_x, verbose=0).argmax(axis=1)
    int8_predictions = scores.argmax(axis=1)
    metrics = {
        "float_test": classification_metrics(test_y, float_predictions),
        "int8_test": classification_metrics(test_y, int8_predictions),
        "float_int8_agreement": float(np.mean(float_predictions == int8_predictions)),
    }
    synthetic = args.synthetic or any(t.session_id.startswith("synthetic_") for t in trials)
    metadata = {
        "dataset_kind": "synthetic_pipeline_check" if synthetic else "recorded_emg",
        "labels": list(LABELS), "csv_columns": list(CSV_COLUMNS),
        "emg_mode": f"pyomyo.emg_mode.{args.mode}", "sample_rate_hz": profile.sample_rate_hz,
        "window_samples": profile.window_samples, "stride_samples": profile.stride_samples,
        "sample_dtype": profile.dtype,
        "features": [f"mav_ch{i}" for i in range(CHANNELS)] +
                    [f"rms_ch{i}" for i in range(CHANNELS)],
        "feature_transform": "log1p" if args.mode == "PREPROCESSED" else "linear",
        "feature_divisor": float(np.log(65536.0)) if args.mode == "PREPROCESSED" else 128.0,
        "quantization": quantization,
        "sessions": {name: sorted({t.session_id for t in part})
                     for name, part in parts.items()},
        "window_counts": counts,
        "source_format": "pyomyo_manifest" if args.pyomyo_manifest else "labeled_csv",
        "sources": [str(args.pyomyo_manifest)] if args.pyomyo_manifest else [str(p) for p in args.data],
        "seed": args.seed, "epochs_run": len(history.history["loss"]),
        "tensorflow_version": tf.__version__, "model_bytes": len(model_bytes),
        "required_micro_ops": ["FullyConnected", "Softmax"], "metrics": metrics,
    }
    args.output.mkdir(parents=True, exist_ok=True)
    model.save(args.output / "emg_model.keras")
    (args.output / "emg_model_int8.tflite").write_bytes(model_bytes)
    write_cpp_model(args.output, model_bytes)
    # Compile this alongside emg_features.h to select exactly the trained mode.
    cpp_mode = {"RAW": "kRaw", "FILTERED": "kFiltered", "PREPROCESSED": "kPreprocessed"}[args.mode]
    (args.output / "emg_preprocessing.h").write_text(
        '#ifndef EMG_PREPROCESSING_H_\n#define EMG_PREPROCESSING_H_\n'
        '#include "emg_features.h"\n\n'
        f'constexpr emg::Mode kEmgMode = emg::Mode::{cpp_mode};\n'
        f'using EmgSample = {profile.dtype}_t;\n'
        f'constexpr int kEmgWindowSamples = {profile.window_samples};\n'
        f'constexpr int kEmgStrideSamples = {profile.stride_samples};\n'
        '#endif\n')
    (args.output / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")

    # Raw windows plus desktop int8 outputs exercise C++ preprocessing AND TFLM.
    with (args.output / "verification.csv").open("w", newline="") as destination:
        writer = csv.writer(destination)
        writer.writerow([f"sample{s}_ch{c}" for s in range(profile.window_samples)
                         for c in range(CHANNELS)] + [f"score_{label}" for label in LABELS])
        for label in range(len(LABELS)):
            for index in np.flatnonzero(test_y == label)[:10]:
                writer.writerow(test_windows[index].ravel().tolist() + scores[index].tolist())
    print(json.dumps(metrics, indent=2))
    print(f"Exported {len(model_bytes)} bytes to {args.output}")
    if synthetic:
        print("SYNTHETIC DATA: this checks the pipeline, not real gesture recognition.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument("--data", type=Path, nargs="+")
    inputs.add_argument("--pyomyo-manifest", type=Path,
                        help="Manifest describing pyomyo Channel_1..8 CSVs or vals*.dat slices")
    parser.add_argument("--mode", choices=PROFILES, default="RAW",
                        help="Recording mode; must match acquisition and deployment")
    parser.add_argument("--validation-session", required=True)
    parser.add_argument("--test-session", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=60)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--synthetic", action="store_true", help="Mark export as synthetic")
    args = parser.parse_args()
    if args.epochs < 1 or args.batch_size < 1:
        parser.error("epochs and batch-size must be positive")
    try:
        train(args)
    except (ValueError, OSError) as error:
        parser.exit(1, f"Error: {error}\n")


if __name__ == "__main__":
    main()
